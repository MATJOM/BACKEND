package com.matjom.matjom.moderation.profanity;

/**
 * 금칙어 검증을 위한 필터 인터페이스.
 * 사용 목적: 리뷰 등 사용자 입력 텍스트를 검증하는 전략을 통합한다.
 * 코드 의미: 구현체가 검증 로직을 제공하도록 단일 메서드를 정의한다.
 * 기대 결과: 검증 실패 시 예외를 던져 상위 레이어에서 요청을 차단한다.
 */
public interface ProfanityFilter {
    /**
     * 주어진 텍스트에 금칙어가 포함됐는지 검사한다.
     * 사용 목적: 컨트롤러/서비스에서 입력값을 선제적으로 걸러낸다.
     * 코드 의미: 구현체가 검증 후 필요하다면 도메인 예외를 발생시킨다.
     * 기대 결과: 금칙어가 없으면 정상 종료, 있다면 예외가 던져진다.
     */
    void validate(String text);
}
